// Turns collect.mjs's data into the tables the audit doc quotes (output/report.md) and the
// short summary it prints. No measuring happens here.

import { againstScale } from "./measure.mjs"

const SHORT = {
  "argus/email": "a-em",
  "argus/watchtower": "wt",
  "email/email": "em",
  "ops-hub/ops-hub-web": "ops",
  "myargus/briefings": "brf",
  "myargus/jobs": "job",
  "myargus/knowledge": "kno",
  "myargus/reader": "rdr",
  "myargus/shell": "shl",
  "myargus/stockade": "stk",
  "homelab/scan-app": "scan",
  "quick-capture/web": "qc",
  atto1: "atto",
  "budget/web": "bud",
  sparky: "spk",
  "slate-reader/server": "sl-s",
  "slate-reader/client": "sl-c",
}

const table = (head, rows) => [`| ${head.join(" | ")} |`, `|${head.map(() => "---").join("|")}|`, ...rows.map((row) => `| ${row.join(" | ")} |`)].join("\n")
const sum = (values) => values.reduce((total, value) => total + value, 0)
const percent = (part, whole) => (whole === 0 ? "n/a" : `${Math.round((part / whole) * 100)}%`)
const order = (tag) => tag.slice(1).split(".").map(Number).reduce((total, part) => total * 1000 + part, 0)

function histogram(counts) {
  const entries = Object.entries(counts).sort((a, b) => (a[0] === "full" ? 1e9 : Number(a[0])) - (b[0] === "full" ? 1e9 : Number(b[0])))
  return entries.length === 0 ? "none" : entries.map(([key, count]) => `${key}×${count}`).join(", ")
}

function heights(counts) {
  const merged = {}
  for (const [key, count] of Object.entries(counts)) merged[key.split(":")[1]] = (merged[key.split(":")[1]] ?? 0) + count
  return histogram(merged)
}

// used-count, then a drift mark. Blank is absent.
function cell(copies) {
  if (copies.length === 0) return ""
  const use = copies.some((copy) => copy.use === "used") ? String(Math.max(...copies.map((copy) => copy.appImporters))) : copies.some((copy) => copy.use === "dependency") ? "d" : "0"
  const states = copies.map((copy) => copy.state)
  const mark = states.includes("forked") ? "F" : states.includes("local-edit") ? "*" : states.includes("stale") ? "~" : ""
  return use + mark
}

function staleKind(copy, pin) {
  if (copy.state !== "stale") return copy.state
  if (copy.matchesPin) return "stale, at pin"
  if (!pin) return "stale, no pin"
  return order(copy.matches[1]) < order(pin) ? "stale, behind pin" : "stale, ahead of pin"
}

function hardcoded(counts) {
  return sum(Object.values(counts.arbitraryLiteral)) + counts.rawColours + counts.inlineStyleLiterals + counts.paletteColourClasses
}

export function renderReport(data) {
  const { apps, registry, cross, scale } = data
  const ui = new Set(registry.ui)
  const out = []
  const push = (...lines) => out.push(...lines, "")

  push(
    "# Primitives usage: collected data",
    "",
    `Generated by \`node docs/audits/primitives-usage/collect.mjs\`. Registry reference: \`${registry.ref}\` (\`${registry.sha}\`), ${registry.ui.length} \`registry:ui\` items, ${registry.blocks.length} blocks, ${registry.tags} release tags compared. Do not edit by hand: re-run the script.`,
  )

  push(
    "## 1. Apps",
    "",
    table(
      ["Key", "App", "Path", "`origin/main`", "Pin", "`components.json`", "Framework", "Files: own + registry copies", "Headless deps in `package.json`"],
      apps.map((app) => [
        SHORT[app.id],
        app.id + (app.mirrorOf ? ` (same app as ${app.mirrorOf})` : ""),
        `\`${app.path}\``,
        `\`${app.sha}\``,
        app.pin ?? "none",
        app.hasComponentsJson ? app.style : "no",
        app.framework.join(", ") || "none",
        `${app.files.authored} + ${app.files.copies}`,
        app.headlessDependencies.length === 0 ? "none" : app.headlessDependencies.length > 3 ? `${app.headlessDependencies.length} (${app.headlessDependencies.slice(0, 2).join(", ")}, …)` : app.headlessDependencies.join(", "),
      ]),
    ),
  )

  // ---- matrix
  const matrixRows = (type) =>
    registry[type === "ui" ? "ui" : "blocks"]
      .map((name) => ({ name, cells: apps.map((app) => cell(app.copies.filter((copy) => copy.item === name && copy.type === type))) }))
      .filter((row) => row.cells.some((value) => value !== ""))
  push(
    "## 2. Usage matrix",
    "",
    "Cell: the number of the app's own files that import the primitive; `d` = imported only by another registry copy; `0` = present, imported by nothing. Mark: none = identical to the reference tag, `~` = stale (matches an older tag), `*` = local edit, `F` = forked. Blank = not in the app.",
    "",
    "### UI primitives present in at least one app",
    "",
    table(["Primitive", ...apps.map((app) => SHORT[app.id])], matrixRows("ui").map((row) => [`\`${row.name}\``, ...row.cells])),
    "",
    "### Blocks (out of scope, shown for the rows and headers they replace)",
    "",
    table(["Block", ...apps.map((app) => SHORT[app.id])], matrixRows("block").map((row) => [`\`${row.name}\``, ...row.cells])),
  )

  // ---- drift
  const kinds = ["identical", "stale, at pin", "stale, behind pin", "stale, ahead of pin", "stale, no pin", "local-edit", "forked"]
  const driftRow = (app, filter) => {
    const copies = app.copies.filter(filter)
    return kinds.map((kind) => copies.filter((copy) => staleKind(copy, app.pin) === kind).length)
  }
  push(
    "## 3. Drift",
    "",
    "### UI primitives, per app",
    "",
    table(["App", "Pin", "Present", ...kinds], apps.map((app) => [app.id, app.pin ?? "none", app.copies.filter((copy) => copy.type === "ui").length, ...driftRow(app, (copy) => copy.type === "ui")])),
    "",
    "### Every registry file (UI, blocks, lib, hooks, files), per app",
    "",
    table(["App", "Pin", "Present", ...kinds], apps.map((app) => [app.id, app.pin ?? "none", app.copies.length, ...driftRow(app, () => true)])),
  )

  const stale = new Map()
  for (const app of apps) {
    for (const copy of app.copies.filter((candidate) => candidate.state === "stale")) {
      const key = `${copy.file}|${copy.matches[0]}|${copy.matches[1]}`
      if (!stale.has(key)) stale.set(key, { copy, apps: [] })
      stale.get(key).apps.push(SHORT[app.id])
    }
  }
  push(
    "### Stale copies: which release each matches",
    "",
    table(
      ["File", "Type", "Matches tags", "Apps"],
      [...stale.values()].sort((a, b) => a.copy.file.localeCompare(b.copy.file) || order(a.copy.matches[1]) - order(b.copy.matches[1])).map(({ copy, apps: where }) => [`\`${copy.file}\``, copy.type, copy.matches[0] === copy.matches[1] ? copy.matches[0] : `${copy.matches[0]} to ${copy.matches[1]}`, where.join(", ")]),
    ),
  )
  const edits = apps.flatMap((app) => app.copies.filter((copy) => copy.state === "local-edit" || copy.state === "forked").map((copy) => ({ app, copy })))
  push(
    "### Local edits and forks",
    "",
    table(
      ["App", "File", "State", "Nearest tag", "Lines + / −", "First changed line"],
      edits.map(({ app, copy }) => [app.id, `\`${app.repo}/${copy.path}\``, copy.state, copy.nearest, `+${copy.added} / −${copy.removed}`, `\`${(copy.sample.find((line) => line.startsWith("+")) ?? copy.sample[0] ?? "").slice(0, 90).replaceAll("|", "\\|").replaceAll("`", "'")}\``]),
    ),
  )

  push(
    "### Token layer",
    "",
    "Share = the registry's `theme/tokens.css` declarations at that tag that the app's CSS also declares with the same value.",
    "",
    table(
      ["App", "Pin", "Newest tag fully matched", `Share at ${registry.ref}`, `Token names missing vs ${registry.ref}`, "Custom properties not from the registry", "Custom properties declared"],
      apps.filter((app) => app.theme).map((app) => [app.id, app.pin ?? "none", app.theme.bestShare === 1 ? app.theme.newestFullMatch : `none (best ${app.theme.newestFullMatch}, ${percent(app.theme.bestShare, 1)})`, percent(app.theme.atRef, 1), app.theme.missingAtRef, app.theme.localNames, app.theme.declared]),
    ),
  )

  // ---- use
  const notImported = apps.flatMap((app) => app.copies.filter((copy) => copy.type === "ui" && copy.use !== "used" && copy.state !== "forked").map((copy) => ({ app, copy })))
  push(
    "## 4. Present but not imported by app code",
    "",
    table(["App", "Never imported at all", "Imported only by another registry copy"], apps.map((app) => {
      const mine = notImported.filter((entry) => entry.app === app)
      const names = (use) => mine.filter((entry) => entry.copy.use === use).map((entry) => `\`${entry.copy.item}\``).join(", ") || "none"
      return [app.id, names("unused"), names("dependency")]
    })),
  )

  // ---- bypass
  push(
    "## 5. Bypass",
    "",
    "### Headless imports, raw elements and same-named local components in the app's own files",
    "",
    table(
      ["App", "Direct headless imports", "Raw elements a primitive covers", "Local components named like a registry export", "Own files in the `ui` directory"],
      apps.map((app) => [
        app.id,
        app.headless.length === 0 ? "0" : `${app.headless.length}: ${[...new Set(app.headless.map((entry) => entry.specifier))].join(", ")}`,
        Object.entries(app.rawElements).map(([element, info]) => `\`<${element}>\`×${info.count}`).join(", ") || "none",
        app.duplicates.map((duplicate) => `\`${duplicate.name}\` (${duplicate.where})`).join("; ") || "none",
        app.localUi.map((path) => `\`${path.split("/").at(-1)}\``).join(", ") || "none",
      ]),
    ),
    "",
    "### Raw elements, by file",
    "",
    table(
      ["App", "Element", "Registry primitive", "Count", "Files (count)"],
      apps.flatMap((app) => Object.entries(app.rawElements).map(([element, info]) => [app.id, `\`<${element}>\``, data.rawElementPrimitive[element], info.count, info.files.sort((a, b) => b.count - a.count).slice(0, 4).map((file) => `\`${file.path}\` (${file.count})`).join(", ") + (info.files.length > 4 ? `, +${info.files.length - 4} more` : "")])),
    ),
  )

  // ---- tokens vs hardcode
  push(
    "## 6. Token use against hardcoding (the app's own files only)",
    "",
    "Token use = semantic colour classes (`bg-primary`, `text-muted-foreground`) plus `var(--token)` references to a registry token. Hardcoded = Tailwind palette classes (`bg-red-500`), raw colours (hex and `rgb()`/`oklch()`-style functions), arbitrary values with a literal (`text-[13px]`), and inline `style` sizes with a literal.",
    "",
    table(
      ["App", "Semantic colour classes", "`var(--token)`", "`var()` of an app-local property", "Palette classes", "Raw colours", "Arbitrary literal: text / spacing / size / radius / colour / other", "Arbitrary, var-backed", "Inline style sizes", "Hardcoded total", "Token share"],
      apps.map((app) => {
        const counts = app.totals.authored
        const tokens = counts.semanticColourClasses + counts.tokenVarUses
        const literal = counts.arbitraryLiteral
        return [app.id, counts.semanticColourClasses, counts.tokenVarUses, counts.localVarUses, counts.paletteColourClasses, counts.rawColours, `${literal.text} / ${literal.spacing} / ${literal.size} / ${literal.radius} / ${literal.colour} / ${literal.other}`, counts.arbitraryVarBacked, counts.inlineStyleLiterals, hardcoded(counts), percent(tokens, tokens + hardcoded(counts))]
      }),
    ),
    "",
    "### Top offenders",
    "",
    table(["App", "File", "Hardcoded values"], apps.flatMap((app) => app.topHardcoded.slice(0, 3).map((file) => [app.id, `\`${file.path}\``, file.hardcoded]))),
    "",
    "### Most common arbitrary values and raw colours",
    "",
    table(
      ["App", "Arbitrary values (count)", "Raw colours (count)"],
      apps.map((app) => {
        const top = (examples) => Object.entries(examples).sort((a, b) => b[1] - a[1]).slice(0, 5).map(([value, count]) => `\`${value.replaceAll("|", "\\|")}\`×${count}`).join(", ") || "none"
        return [app.id, top(app.totals.authored.arbitraryExamples), top(app.totals.authored.rawColourExamples)]
      }),
    ),
  )

  // ---- 207
  const dimension = (key, field) => [key, field, scale[key]]
  const dimensions = [dimension("type", "fontSize"), dimension("weight", "fontWeight"), dimension("spacing", "spacing"), dimension("radius", "radius")]
  push(
    "## 7. Data for design-system#207",
    "",
    `Proposed scale: type ${scale.type.join("/")}px, weights ${scale.weight.join("/")}, spacing ${scale.spacing.join("/")}px, radius ${scale.radius.join("/")}px. Values are what the source declares (Tailwind classes resolved through the app's own \`--text-*\` and \`--radius\`, arbitrary values, inline styles and app CSS), not what a browser drew. 0 and \`full\` count as neither on nor off the scale.`,
    "",
    "### Histograms, the app's own files (px×occurrences)",
    "",
    table(
      ["App", "Font sizes", "Weights", "Spacing", "Radii", "Control and row heights 24 to 64px (`h-`, `min-h-`, `size-`)"],
      [...apps.map((app) => [app.id, histogram(app.totals.authored.fontSize), histogram(app.totals.authored.fontWeight), histogram(app.totals.authored.spacing), histogram(app.totals.authored.radius), heights(app.totals.authored.height)]), [`registry ${registry.ref} \`ui\` (baseline)`, histogram(registry.baseline.fontSize), histogram(registry.baseline.fontWeight), histogram(registry.baseline.spacing), histogram(registry.baseline.radius), heights(registry.baseline.height)]],
    ),
    "",
    "### Off-scale occurrences, the app's own files",
    "",
    table(
      ["App", "Type off / all", "Weight off / all", "Spacing off / all", "Radius off / all", "All off / all", "Off-scale share", "Files with an off-scale value / own files"],
      [
        ...apps.map((app) => {
          const cells = dimensions.map(([key]) => `${app.offScale[key].off} / ${app.offScale[key].off + app.offScale[key].on}`)
          const off = sum(dimensions.map(([key]) => app.offScale[key].off))
          const all = off + sum(dimensions.map(([key]) => app.offScale[key].on))
          return [app.id, ...cells, `${off} / ${all}`, percent(off, all), `${app.offScaleFiles} / ${app.files.authored}`]
        }),
        (() => {
          const results = dimensions.map(([, field, allowed]) => againstScale(registry.baseline[field], allowed))
          const off = sum(results.map((result) => result.off))
          const all = off + sum(results.map((result) => result.on))
          return [`registry ${registry.ref} \`ui\` (baseline)`, ...results.map((result) => `${result.off} / ${result.off + result.on}`), `${off} / ${all}`, percent(off, all), "n/a"]
        })(),
      ],
    ),
    "",
    "### What moving to the scale would take, the app's own files",
    "",
    "A named step (`text-xs`, `rounded-lg`, `font-medium`) can be moved onto the scale by the theme, with no edit in the app. A literal (an arbitrary value, an inline style, a CSS declaration) and every off-scale spacing class has to be edited in the app's source.",
    "",
    table(
      ["App", "Off-scale type: named / literal", "Off-scale weight: named / literal", "Off-scale radius: named / literal", "Off-scale spacing (all need an edit)", "Covered by a theme remap", "Needs a source edit"],
      apps.map((app) => {
        const counts = app.totals.authored
        const split = (field, allowed) => {
          const all = againstScale(counts[field], allowed).off
          const literal = againstScale(counts[`${field}Literal`] ?? {}, allowed).off
          return [all - literal, literal]
        }
        const type = split("fontSize", scale.type)
        const weight = split("fontWeight", scale.weight)
        const radius = split("radius", scale.radius)
        const spacing = app.offScale.spacing.off
        return [app.id, type.join(" / "), weight.join(" / "), radius.join(" / "), spacing, type[0] + weight[0] + radius[0], type[1] + weight[1] + radius[1] + spacing]
      }),
    ),
    "",
    "### Off-scale values, every app's own files together (mirror copies counted once)",
    "",
    table(
      ["Dimension", "On-scale occurrences", "Off-scale occurrences", "Off-scale values (px×occurrences)"],
      dimensions.map(([key, field, allowed]) => {
        const merged = {}
        for (const app of apps.filter((candidate) => !candidate.mirrorOf)) for (const [value, count] of Object.entries(app.totals.authored[field])) merged[value] = (merged[value] ?? 0) + count
        const result = againstScale(merged, allowed)
        return [key, result.on, result.off, histogram(result.offValues)]
      }),
    ),
    "",
    "### List rows drawn inside `.map()`",
    "",
    "Heuristic, two passes: `mapped` is the first element inside a `.map(` whose class list is a flex or grid row with alignment and its own height or padding; `component` is a local component named `*Row` or `*ListItem`, with the classes of its first element. Read each one before trusting it.",
    "",
    table(
      ["App", "Found as", "Where", "Element", "Height", "Text sizes", "Weights", "Classes"],
      apps.flatMap((app) => (app.mirrorOf ? [] : app.rows.map((row) => [app.id, row.kind, `\`${row.where}\``, `\`<${row.element}>\``, row.height.join(" ") || "none", row.text.join(" ") || "none", row.weight.join(" ") || "none", `\`${row.classes.replace(/\s+/g, " ").slice(0, 110).replaceAll("|", "\\|").replaceAll("`", "'")}\``]))),
    ),
  )

  // ---- unused
  const uiUsage = cross.usage.filter((entry) => entry.type === "ui")
  push(
    "## 8. Unused primitives (mirror copy counted once, forks not counted)",
    "",
    `In no app at all (${uiUsage.filter((entry) => entry.present === 0).length} of ${uiUsage.length}): ${uiUsage.filter((entry) => entry.present === 0).map((entry) => `\`${entry.name}\`${entry.forkedIn.length > 0 ? " (forked copy in budget)" : ""}`).join(", ")}.`,
    "",
    `Installed somewhere but imported by no app code (${uiUsage.filter((entry) => entry.present > 0 && entry.used === 0).length}): ${uiUsage.filter((entry) => entry.present > 0 && entry.used === 0).map((entry) => `\`${entry.name}\``).join(", ") || "none"}.`,
    "",
    table(["Primitive", "Apps present", "Apps importing", "Importing files, all apps", "Used in"], uiUsage.filter((entry) => entry.present > 0).sort((a, b) => b.importingFiles - a.importingFiles).map((entry) => [`\`${entry.name}\``, entry.present, entry.used, entry.importingFiles, entry.usedIn.map((id) => SHORT[id]).join(", ")])),
  )

  // ---- missing
  push(
    "## 9. Local components that repeat across apps",
    "",
    "### Same name in two or more apps",
    "",
    table(["Component", "Apps", "Where"], cross.shared.filter((entry) => !["App", "Home", "Dashboard", "Shell", "Settings"].includes(entry.name)).map((entry) => [`\`${entry.name}\``, entry.apps.length, entry.places.map((place) => `\`${place.where}\``).join(", ")])),
    "",
    "### Same suffix in two or more apps",
    "",
    table(["Suffix", "Components", "Apps", "Where"], cross.suffixes.map((entry) => [`\`*${entry.suffix}\``, entry.components, entry.apps.length, entry.places.slice(0, 14).map((place) => `\`${place.name}\` (\`${place.where}\`)`).join(", ") + (entry.places.length > 14 ? `, +${entry.places.length - 14} more` : "")])),
  )

  // ---- summary
  const consumers = apps.filter((app) => app.pin)
  const uiCopies = apps.filter((app) => !app.mirrorOf).flatMap((app) => app.copies.filter((copy) => copy.type === "ui"))
  const count = (state) => uiCopies.filter((copy) => copy.state === state).length
  const summary = [
    `registry ${registry.ref} (${registry.sha}): ${registry.ui.length} ui primitives, ${registry.tags} tags compared`,
    `apps: ${apps.length} measured, ${consumers.length} with a @design-system pin (${[...new Set(consumers.map((app) => app.pin))].sort((a, b) => order(a) - order(b)).map((pin) => `${pin}×${consumers.filter((app) => app.pin === pin).length}`).join(", ")})`,
    `ui primitives in no app: ${uiUsage.filter((entry) => entry.present === 0).length} of ${uiUsage.length}; installed but never imported by app code: ${uiUsage.filter((entry) => entry.present > 0 && entry.used === 0).length}`,
    `ui copies (mirror counted once): ${uiCopies.length} = identical ${count("identical")}, stale ${count("stale")}, local-edit ${count("local-edit")}, forked ${count("forked")}`,
    `direct headless imports in app code: ${sum(apps.filter((app) => !app.mirrorOf).map((app) => app.headless.length))}; raw elements a primitive covers: ${sum(apps.filter((app) => !app.mirrorOf).flatMap((app) => Object.values(app.rawElements).map((info) => info.count)))}`,
    ...apps.map((app) => {
      const off = sum(dimensions.map(([key]) => app.offScale[key].off))
      const all = off + sum(dimensions.map(([key]) => app.offScale[key].on))
      return `  ${app.id.padEnd(22)} pin ${String(app.pin ?? "none").padEnd(8)} ui ${String(app.copies.filter((copy) => copy.type === "ui").length).padStart(2)}  hardcoded ${String(hardcoded(app.totals.authored)).padStart(4)}  off-scale ${String(off).padStart(4)}/${String(all).padEnd(4)} ${percent(off, all)}`
    }),
    "wrote output/data.json and output/report.md",
    "",
  ].join("\n")

  return { markdown: out.join("\n").trimEnd() + "\n", summary }
}
