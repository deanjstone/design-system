#!/usr/bin/env node
// Reads every screens/<app>/scorecard.json and writes output/scorecard.md: which scorecard
// lines each screen passes, how often each line fails, and the measurements behind the failures.
// It renders nothing, so it can run anywhere.
//
//   node docs/audits/primitives-usage/scores.mjs

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const here = path.dirname(fileURLToPath(import.meta.url))
const table = (head, rows) => [`| ${head.join(" | ")} |`, `|${head.map(() => "---").join("|")}|`, ...rows.map((row) => `| ${row.join(" | ")} |`)].join("\n")
const cell = (text) => String(text).replaceAll("|", "\\|").replaceAll("\n", " ")

const apps = readdirSync(path.join(here, "screens"))
  .filter((name) => existsSync(path.join(here, "screens", name, "scorecard.json")))
  .sort()
  .map((name) => ({ name, config: JSON.parse(readFileSync(path.join(here, "screens", name, "config.json"), "utf8")), card: JSON.parse(readFileSync(path.join(here, "screens", name, "scorecard.json"), "utf8")) }))

const screens = apps.flatMap((app) => app.card.screens.filter((screen) => !screen.checks.error).map((screen) => ({ app: app.name, baseline: app.name === "ds-sample" || app.name === "proposed", ...screen })))
const lines = []
for (const screen of screens) for (const [need, checks] of Object.entries(screen.checks)) for (const name of Object.keys(checks)) if (!lines.some((line) => line.need === need && line.name === name)) lines.push({ need, name })
const mark = (check) => (!check || check.pass === null ? "–" : check.pass ? "✓" : "✗")
const phone = (screen) => screen.variants["iphone-light"]
const out = []
const push = (...text) => out.push(...text, "")

push("# Reading scorecard: collected results", "", `Generated by \`node docs/audits/primitives-usage/scores.mjs\` from ${apps.length} apps' \`screens/<app>/scorecard.json\` (${screens.length} screens). Do not edit by hand. ✓ pass, ✗ fail, – not applicable. iPhone is 390×844 WebKit, touch, light theme unless a line says otherwise.`)

push("## 1. What was rendered", "", table(["App", "Repo at", "Screen", "Path", "Why this screen"], apps.flatMap((app) => app.card.screens.map((screen) => [app.name, `\`${app.config.repo}@${app.config.sha ?? "?"}\``, screen.name, `\`${screen.path}\``, cell(screen.why)]))))

const needs = [...new Set(lines.map((line) => line.need))]
for (const need of needs) {
  const mine = lines.filter((line) => line.need === need)
  push(`## 2. ${need}`, "", table(["Screen", ...mine.map((line) => line.name)], screens.map((screen) => [`${screen.app} / ${screen.name}`, ...mine.map((line) => mark(screen.checks[need]?.[line.name]))])))
}

const real = screens.filter((screen) => !screen.baseline)
push(
  "## 3. How often each line fails (app screens only: the registry sample and the proposed samples are left out)",
  "",
  table(
    ["Need", "Line", "Fail", "Pass", "n/a", "Failing screens"],
    lines
      .map((line) => {
        const results = real.map((screen) => ({ screen, check: screen.checks[line.need]?.[line.name] }))
        const failing = results.filter((entry) => entry.check?.pass === false)
        return { line, fail: failing.length, pass: results.filter((entry) => entry.check?.pass === true).length, na: results.filter((entry) => !entry.check || entry.check.pass === null).length, failing }
      })
      .sort((a, b) => b.fail - a.fail)
      .map((row) => [row.line.need, row.line.name, row.fail, row.pass, row.na, row.failing.map((entry) => `${entry.screen.app}/${entry.screen.name}`).join(", ") || "none"]),
  ),
)

const apply = (pick) => screens.map((screen) => [`${screen.app} / ${screen.name}`, ...pick(screen)])
push(
  "## 4. Measurements, iPhone",
  "",
  "### Type and hierarchy",
  "",
  table(["Screen", "Font sizes in the first viewport (px)", "Largest text", "Body text (px)", "h1 on show", "Heading weights", "Row title weight"], apply((screen) => {
    const raw = phone(screen)
    return [raw.hierarchy.fontSizes.map((entry) => entry.size).join(" / "), cell(`${raw.hierarchy.largest.size}px ×${raw.hierarchy.largest.elements} "${raw.hierarchy.largest.text}"`), raw.reading.bodySize ?? "none", raw.hierarchy.headings.some((heading) => heading.tag === "h1") ? "yes" : "no", [...new Set(raw.hierarchy.headings.map((heading) => heading.weight))].join(" / ") || "none", raw.rows.count ? raw.rows.titleWeightMax : "no rows"]
  })),
  "",
  "### Rows, clutter and controls",
  "",
  table(["Screen", "Rows", "Row heights (px)", "Most chips in a row", "Most colours in a row", "Texts cut short (in rows)", "Controls in the first viewport", "Alpha steps", "Tap targets under 44px", "Inputs under 16px"], apply((screen) => {
    const raw = phone(screen)
    return [raw.rows.count, raw.rows.heights.join(" / ") || "none", raw.rows.maxChips, raw.rows.maxColours, raw.truncated ? `${raw.truncated.count} (${raw.truncated.inRows})` : "n/a", raw.interactive.firstViewport, raw.alphaSteps.length, `${raw.interactive.small} of ${raw.interactive.measured}`, `${raw.interactive.smallInputs.length} of ${raw.interactive.inputs}`]
  })),
  "",
  "### Small tap targets, by control",
  "",
  table(["Screen", "Controls under 44px (width×height)"], screens.filter((screen) => phone(screen).interactive.small > 0).map((screen) => [`${screen.app} / ${screen.name}`, cell(phone(screen).interactive.smallSample.map((entry) => `${entry.what} (${entry.tag} ${entry.width}×${entry.height})`).join("; "))])),
  "",
  "### Text cut short",
  "",
  table(["Screen", "Sample (share of the text on show)"], screens.filter((screen) => (phone(screen).truncated?.count ?? 0) > 0).map((screen) => [`${screen.app} / ${screen.name}`, cell(phone(screen).truncated.sample.slice(0, 4).join("; "))])),
  "",
  "### State colour",
  "",
  table(["Screen", "Status-coloured elements", "Colour alone", "Status colours not from a token (hex×count, hue family)"], screens.filter((screen) => phone(screen).state.statusColoured > 0).map((screen) => {
    const state = phone(screen).state
    return [`${screen.app} / ${screen.name}`, state.statusColoured, state.colourOnly, state.offToken.map((entry) => `${entry.colour}×${entry.count} ${entry.family}`).join(", ") || "none"]
  })),
  "",
  "### Contrast failures (WCAG AA), all four renders",
  "",
  table(["Screen", "iPhone light", "iPhone dark", "Desktop light", "Desktop dark", "Worst (ratio, text colour on ground)"], screens.filter((screen) => ["iphone-light", "iphone-dark", "desktop-light", "desktop-dark"].some((name) => (screen.variants[name]?.reading?.contrastFailCount ?? 0) > 0)).map((screen) => {
    const fails = ["iphone-light", "iphone-dark", "desktop-light", "desktop-dark"].map((name) => screen.variants[name]?.reading)
    const worst = fails.flatMap((reading) => reading?.contrastFails ?? []).sort((a, b) => a.ratio - b.ratio)[0]
    return [`${screen.app} / ${screen.name}`, ...fails.map((reading) => reading?.contrastFailCount ?? "n/a"), cell(`"${worst.text}" ${worst.ratio}:1, ${worst.colour} on ${worst.on}`)]
  })),
  "",
  "### Desktop line length and layout",
  "",
  table(["Screen", "Wrapped paragraphs", "Line length (ch)", "Sideways scroll at 390 / 320 (px)", "Text under a floating bar (first viewport)"], apply((screen) => {
    const wide = screen.variants["desktop-light"]?.reading?.lines ?? []
    const lengths = wide.map((line) => line.ch)
    return [wide.length, lengths.length ? `${Math.min(...lengths)} to ${Math.max(...lengths)}` : "none", `${phone(screen).reading.overflowX} / ${screen.variants["iphone-320"]?.reading?.overflowX ?? "n/a"}`, phone(screen).covered?.runs ?? "n/a"]
  })),
)

const blockedAll = apps.flatMap((app) => (app.card.blocked ?? []).map((entry) => [app.name, cell(entry.request), entry.count]))
push("## 5. Requests the apps tried to send off localhost (aborted by the harness)", "", blockedAll.length ? table(["App", "Request", "Times"], blockedAll) : "None.")

writeFileSync(path.join(here, "output", "scorecard.md"), out.join("\n").trimEnd() + "\n")
const fails = real.reduce((sum, screen) => sum + Object.values(screen.checks).flatMap((checks) => Object.values(checks)).filter((check) => check.pass === false).length, 0)
console.log(`scorecard: ${apps.length} apps, ${screens.length} screens, ${fails} failing lines on app screens; wrote output/scorecard.md`)
