// Writes the colour tokens in theme/themes.json into the two hand-kept copies of
// the theme: theme/tokens.css and the "theme" item in registry.json.
//
//   node scripts/theme/build.mjs
//
// Then regenerate r/ with `npx shadcn build --output ./r`.
//
// Ocean is the default: it is the plain :root / .dark rule, so a page with no
// data-theme attribute is Ocean. Every theme, Ocean included, also answers to
// [data-theme="<name>"] and [data-theme="<name>"].dark, on any element, so a
// picker can preview a theme inside another. A theme's .dark rule has one more
// part than the bare .dark rule, which is what lets it win.

import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

import { MODES, THEME_NAMES, TOKEN_MAP } from "./extract-t3.mjs"
import { STATUS_TOKENS } from "./status.mjs"

export const DEFAULT_THEME = "ocean"
const BEGIN = "/* theme:begin"
const END = "/* theme:end */"

const darkSelector = (theme) => `[data-theme="${theme}"].dark`
const lightSelector = (theme) => `[data-theme="${theme}"]`

// Rules in cascade order: Ocean's bare :root/.dark first, then each theme's own pair.
// The status tokens ride on the bare rules only; every theme inherits them.
function themeRules(themes) {
  const rules = []
  const tokensOf = (theme, mode) => themes[theme][mode]
  rules.push({
    selectors: [":root", lightSelector(DEFAULT_THEME)],
    tokens: { ...tokensOf(DEFAULT_THEME, "light"), ...STATUS_TOKENS.light },
  })
  rules.push({
    selectors: [".dark", darkSelector(DEFAULT_THEME)],
    tokens: { ...tokensOf(DEFAULT_THEME, "dark"), ...STATUS_TOKENS.dark },
  })
  for (const theme of THEME_NAMES.filter((name) => name !== DEFAULT_THEME)) {
    rules.push({ selectors: [lightSelector(theme)], tokens: tokensOf(theme, "light") })
    rules.push({ selectors: [darkSelector(theme)], tokens: tokensOf(theme, "dark") })
  }
  return rules
}

const STATUS_NAMES = Object.keys(STATUS_TOKENS.light)

const cssBlock = ({ selectors, tokens }) => {
  const names = [...Object.keys(TOKEN_MAP), ...STATUS_NAMES.filter((token) => token in tokens)]
  return `${selectors.join(",\n")} {\n${names.map((token) => `  --${token}: ${tokens[token]};`).join("\n")}\n}\n`
}

export function renderThemeCss(themes) {
  return themeRules(themes).map(cssBlock).join("\n")
}

export function applyToTokensCss(css, themes, sha = readSha()) {
  const start = css.indexOf(BEGIN)
  const end = css.indexOf(END)
  if (start === -1 || end === -1) throw new Error("tokens.css has no theme:begin / theme:end markers")
  const header =
    `${BEGIN} — generated by scripts/theme/build.mjs from theme/themes.json,\n` +
    `   read from pingdotgg/t3code at ${sha}. Edit themes.json, not this region. */\n`
  return `${css.slice(0, start)}${header}${renderThemeCss(themes)}${css.slice(end)}`
}

export function applyToRegistry(registry, themes) {
  const next = structuredClone(registry)
  const item = next.items.find((entry) => entry.name === "theme")
  const light = { ...themes[DEFAULT_THEME].light, ...STATUS_TOKENS.light }
  const dark = { ...themes[DEFAULT_THEME].dark, ...STATUS_TOKENS.dark }

  const replaceTokens = (existing, tokens) => {
    const merged = {}
    for (const [key, value] of Object.entries(existing)) merged[key] = key in tokens ? tokens[key] : value
    for (const token of [...Object.keys(TOKEN_MAP), ...STATUS_NAMES]) merged[token] ??= tokens[token]
    return merged
  }
  item.cssVars.light = replaceTokens(item.cssVars.light, light)
  item.cssVars.dark = replaceTokens(item.cssVars.dark, dark)
  for (const token of STATUS_NAMES) {
    item.cssVars.theme[`color-${token}`] = `var(--${token})`
  }

  const declarations = (tokens) =>
    Object.fromEntries(Object.keys(TOKEN_MAP).map((token) => [`--${token}`, tokens[token]]))
  const generated = {}
  for (const theme of THEME_NAMES) {
    generated[lightSelector(theme)] = declarations(themes[theme].light)
    generated[darkSelector(theme)] = declarations(themes[theme].dark)
  }

  const css = {}
  for (const [key, value] of Object.entries(item.css)) {
    if (key.startsWith("[data-theme=")) continue
    css[key] = value
    if (key.startsWith("@custom-variant wco")) Object.assign(css, generated)
  }
  item.css = css
  return next
}

function readSha() {
  const source = JSON.parse(readFileSync(fileURLToPath(new URL("../../theme/themes.json", import.meta.url)), "utf8"))
  return source.source.sha
}

const main = () => {
  const path = (relative) => fileURLToPath(new URL(relative, import.meta.url))
  const { themes, source } = JSON.parse(readFileSync(path("../../theme/themes.json"), "utf8"))
  const tokensPath = path("../../theme/tokens.css")
  writeFileSync(tokensPath, applyToTokensCss(readFileSync(tokensPath, "utf8"), themes, source.sha))
  const registryPath = path("../../registry.json")
  const registry = JSON.parse(readFileSync(registryPath, "utf8"))
  writeFileSync(registryPath, `${JSON.stringify(applyToRegistry(registry, themes), null, 2)}\n`)
  console.log("wrote theme/tokens.css and registry.json; now run: npx shadcn build --output ./r")
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main()
